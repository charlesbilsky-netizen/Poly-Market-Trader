    versionCode = 5
    versionName = "3.1"
    multiDexEnabled = true

    testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
  }

  signingConfigs {
    create("release") {
      // Sideload signing key. The keystore is committed on purpose so every
      // build — local, CI, or a friend's machine — signs with the SAME key
      // and installs cleanly as an update. This is NOT a Play upload key;
      // if the app ever goes to Play, generate a fresh private keystore.
      val keystorePath = System.getenv("KEYSTORE_PATH") ?: "${rootDir}/sideload-keystore.jks"
      storeFile = file(keystorePath)
      storePassword = System.getenv("STORE_PASSWORD") ?: "polytrader-sideload"
      keyAlias = System.getenv("KEY_ALIAS") ?: "upload"
      keyPassword = System.getenv("KEY_PASSWORD") ?: "polytrader-sideload"
    }
  }

